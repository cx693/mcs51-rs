; ===========================================================================
;  流水灯 —— STC89C52RC / 8051 入门工程
;  LED chaser on P3.5 / P3.6 / P3.7
;
;  硬件接线（低电平点亮，最常见的共阳接法）
;  ---------------------------------------------------------------
;       VCC ──►|── LED1 ──[330Ω]── P3.5
;       VCC ──►|── LED2 ──[330Ω]── P3.6
;       VCC ──►|── LED3 ──[330Ω]── P3.7
;
;  为什么用 P3.5 / P3.6 / P3.7：
;       P3.0 = RXD、P3.1 = TXD —— 下载程序时要用，必须留着；
;       P3.2 = INT0、P3.3 = INT1 —— 留给外部中断；
;       P3.4 = T0 计数输入；
;       P3.5 = T1、P3.6 = WR、P3.7 = RD —— 不用定时器和外部存储器时，
;       这三根是干净的普通 IO，拿来点灯最合适。
;
;  行为：三只 LED 依次点亮，每只亮约 250ms，循环往复。
;
;  构建： mcs51 build examples/led-flow
;  下载： mcs51 flash examples/led-flow -p /dev/ttyUSB0 -r dtr
;  模拟： mcs51 flash examples/led-flow --simulate
;
;  注意：本文件全部使用中文注释，代码本身是标准 8051 汇编，
;        由本项目的 mcs51-asm 汇编器直接汇编，不依赖 SDCC。
; ===========================================================================

        .include "8051.inc"          ; SFR 与位地址定义（汇编器内建，可省略）

; ---------------------------------------------------------------------------
;  复位向量
; ---------------------------------------------------------------------------
        .area CODE (ABS)             ; 绝对定位的代码段
        .org  0x0000                 ; 8051 上电后固定从 0x0000 开始取指
        LJMP  main                   ; 跳到主程序（0x0030）

; ---------------------------------------------------------------------------
;  中断向量表
;
;  本工程不使用任何中断，但向量表必须存在：万一有干扰触发了中断，
;  若落到未初始化的 0xFF 上就会跑飞。这里全部填 RETI（中断返回）。
; ---------------------------------------------------------------------------
        .org  0x0003
        RETI                         ; 外部中断 0（INT0，P3.2）
        .org  0x000B
        RETI                         ; 定时器 0 溢出
        .org  0x0013
        RETI                         ; 外部中断 1（INT1，P3.3）
        .org  0x001B
        RETI                         ; 定时器 1 溢出
        .org  0x0023
        RETI                         ; 串口收发
        .org  0x002B
        RETI                         ; 定时器 2（8052 才有）

; ---------------------------------------------------------------------------
;  main —— 主程序
; ---------------------------------------------------------------------------
        .org  0x0030
main:
        MOV   SP, #0x30              ; 设置堆栈指针：0x30 以上的内部 RAM 不使用，
                                     ; 给堆栈留出 0x30~0x7F 共 80 字节空间。
                                     ; 复位后 SP=0x07，若不重设，第一次压栈就会
                                     ; 覆盖寄存器组 1（0x08~0x0F）。

        ACALL leds_off               ; 上电先把三只灯都熄灭，
                                     ; 避免下载完的一瞬间三个灯全亮

; ---------------------------------------------------------------------------
;  chase —— 流水灯主循环：P3.5 → P3.6 → P3.7 → 回到 P3.5
;
;  这里用 SETB / CLR 位操作而不是 MOV P3,#立即数，
;  原因是位操作只改目标引脚，不影响 P3 上其它位
;  （尤其是 P3.0/P3.1 串口脚和 P3.2/P3.3 中断脚）。
; ---------------------------------------------------------------------------
chase:
        CLR   P35                   ; 第 1 只亮（低电平导通）
        ACALL delay                  ; 保持约 250ms
        SETB  P35                   ; 第 1 只灭

        CLR   P36                   ; 第 2 只亮
        ACALL delay
        SETB  P36

        CLR   P37                   ; 第 3 只亮
        ACALL delay
        SETB  P37

        SJMP  chase                  ; 回到开头，形成循环流水

; ---------------------------------------------------------------------------
;  leds_off —— 熄灭全部三只 LED
;  入口：无        出口：无        破坏：无（只动 P3.5/P3.6/P3.7）
; ---------------------------------------------------------------------------
leds_off:
        SETB  P35                   ; 输出高电平 → LED 无电流 → 灭
        SETB  P36
        SETB  P37
        RET

; ---------------------------------------------------------------------------
;  delay —— 软件延时，约 250ms
;
;  入口：无        出口：无        破坏：R5、R6、R7、PSW
;
;  算法：三层嵌套空循环。
;        DJNZ 是 2 个机器周期；12MHz 晶振下 1 个机器周期 = 1us。
;        2 × 250（内） × 250（中） × 2（外） ≈ 250,000 个机器周期
;        ≈ 250ms。
;
;  想改流水速度：把 R5 改成 1 就是约 125ms，改成 4 就是约 500ms。
;  芯片是 11.0592MHz 时同参数约 271ms，肉眼没有区别。
; ---------------------------------------------------------------------------
delay:
        MOV   R5, #2                 ; 外层循环次数
delay_outer:
        MOV   R6, #250               ; 中层循环次数
delay_middle:
        MOV   R7, #250               ; 内层循环次数
delay_inner:
        DJNZ  R7, delay_inner        ; R7 减 1，不为 0 就继续内层
        DJNZ  R6, delay_middle       ; 内层跑完，中层减 1
        DJNZ  R5, delay_outer        ; 中层跑完，外层减 1
        RET

        .end                         ; 源文件结束
