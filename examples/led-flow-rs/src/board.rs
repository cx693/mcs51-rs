//! 板级参数：晶振、Timer 0 时基、PWM 参数、引脚分配。
//!
//! 硬件相关的数字**只在这一个文件里出现**。换板子只改这里，
//! 呼吸灯（[`crate::breath`]）和流水灯（[`crate::leds`]）的逻辑都不用动。

use mcs51_chips::stc89c5xrc::*;
use mcs51_codegen::prelude::*;

/// 外部晶振：11.0592 MHz（8051 的标准晶振）。
pub const CRYSTAL_HZ: u32 = 11_059_200;

/// 一个机器周期多少个时钟（经典 8051）。
pub const CLOCKS_PER_CYCLE: u32 = 12;

/// 每秒多少个机器周期。11.0592MHz / 12 = 921600。
pub const MACHINE_CYCLES_PER_SECOND: u32 = CRYSTAL_HZ / CLOCKS_PER_CYCLE;

// ---------------------------------------------------------------------------
// 编译期检查：参数算错了就别想编过
// ---------------------------------------------------------------------------

const _: () = {
    // HAL 算出来的重载值必须落在合理范围（不能大到一溢出就重来）。
    let counted = MACHINE_CYCLES_PER_SECOND * TICK_MICROS / 1_000_000 - TICK_OVERHEAD;
    assert!(counted > 100 && counted < 60_000, "Timer 0 周期不合理");

    // PWM 频率必须远高于人眼闪烁阈值（60Hz），否则看着在抖。
    let timer_hz = MACHINE_CYCLES_PER_SECOND / counted;
    let pwm_hz = timer_hz / PWM_PERIOD as u32;
    assert!(pwm_hz > 80, "PWM 频率太低，会看到闪烁");

    // 占空比至少要 20 档，否则呼吸是"跳"的而不是"匀"的。
    assert!(PWM_PERIOD >= 20, "占空比分辨率太低，呼吸会一格一格的");

    // 一个完整呼吸周期（上去再下来）应该在一秒到十秒之间，太慢看不出、太快像闪。
    let breath_ms = (PWM_PERIOD as u32 * RAMP_HOLD as u32 * 2 * 1000) / pwm_hz;
    assert!(
        breath_ms > 1000 && breath_ms < 10_000,
        "一次呼吸的时长不自然"
    );
};

// ---------------------------------------------------------------------------
// Timer 0 时基
// ---------------------------------------------------------------------------

/// 晶振频率，给 HAL 算定时器重载值和串口分频用。
pub const CPU_HZ: u32 = CRYSTAL_HZ;

/// Timer 0 的溢出周期，单位微秒。
///
/// 这个数字是**整个设计的地基**：PWM 的占空比分辨率、呼吸快慢、
/// 流水灯换灯间隔全都从它推出来。
///
/// 11.0592MHz 下 200us = **184.32 个机器周期**；扣掉下面那 16 个周期的软件开销，
/// `Timer` 会装 168，实际周期 168 + 16 = 184 周期 = 200us。
pub const TICK_MICROS: u32 = 200;

/// "主循环发现溢出 → 清标志 → 重装"这一段占用的机器周期。
///
/// 定时器在软件反应过来之前**已经在继续计数了**，所以实际周期是
/// `重载值 + 这段开销`。周期长时无所谓，周期只有一百多个机器周期时
/// 不扣会明显偏慢。这个值是按生成代码数出来的（`JNB` + `CLR` + 两条 `MOV`）。
pub const TICK_OVERHEAD: u32 = 16;

// ---------------------------------------------------------------------------
// 呼吸灯参数（P3.7）
// ---------------------------------------------------------------------------

/// 一个 PWM 周期有多少个 tick。50 × 0.2ms = 10ms → 100Hz，肉眼看不到闪。
pub const PWM_PERIOD: u8 = 50;

/// 占空比每隔几个 PWM 周期变一格。
///
/// 51 档 × 6 × 10ms ≈ 3 秒一个完整呼吸，正好是舒服的节奏。
pub const RAMP_HOLD: u8 = 6;

/// 呼吸灯引脚。
pub const BREATH_PIN: Bit = P37;

// ---------------------------------------------------------------------------
// 流水灯参数（P3.5 / P3.6）
// ---------------------------------------------------------------------------

/// 做流水的引脚。**数组顺序就是流水顺序。**
///
/// P3.7 不在里面 —— 它被呼吸灯占了。
pub const CHASE_LEDS: [Bit; 2] = [P35, P36];

/// 每只灯亮多久（毫秒）。
pub const DWELL_MS: u32 = 250;

/// 流水灯换灯要等几个 PWM 周期。25 × 10ms = 250ms。
pub const CHASE_PERIODS: u8 = (DWELL_MS / 10) as u8;

// ---------------------------------------------------------------------------
// Timer 0 的 SFR 地址
// ---------------------------------------------------------------------------

// Timer 0 的寄存器直接用芯片标准库的定义（`use mcs51_chips::stc89c5xrc::*`），
// 不再需要在这里降级成 u8 地址常量 —— eDSL 的接口现在直接吃 `Sfr`。

// ---------------------------------------------------------------------------
// 目标芯片（来自芯片标准库 mcs51-chips）
// ---------------------------------------------------------------------------

/// 目标型号。
pub const CHIP_MODEL: &str = CHIP.name;

/// Flash 大小。产物超过它就该在构建期报错，而不是烧进去才发现。
pub const FLASH_BYTES: usize = CHIP.flash_bytes;

/// 内部 RAM 字节数。
pub const IDATA_BYTES: usize = CHIP.idata_bytes;

const _: () = {
    // 板子上的片子和这里写死的型号必须对得上 —— 换芯片时改这一处。
    assert!(FLASH_BYTES == 8 * 1024, "STC89C52RC 是 8KB Flash");
    assert!(IDATA_BYTES == 256, "STC89C52RC 有 256 字节内部 RAM");
    // Timer 0 的寄存器地址必须来自芯片库，不是手抄的。
    assert!(TMOD.addr == 0x89);
    assert!(TR0.addr == 0x8C);
};

/// 组装一个板级配置。
pub fn board(name: &str) -> Board {
    Board::default()
        .named(name)
        .device(CHIP_MODEL)
        .crystal(CRYSTAL_HZ)
        .baud(9600)
}
