//! Project manifests (`mcs51.toml`).
//!
//! The format is a small, deliberately boring subset of TOML: sections, scalar
//! keys and flat arrays of strings. It is parsed here rather than pulled in as a
//! dependency, which keeps the toolchain self-contained.

use std::collections::BTreeMap;
use std::fmt;
use std::path::{Path, PathBuf};

/// A parsed manifest.
#[derive(Debug, Clone, Default)]
pub struct Manifest {
    /// Path the manifest was read from.
    pub path: PathBuf,
    /// Directory containing the manifest: all relative paths resolve from here.
    pub root: PathBuf,
    /// `[project]`
    pub project: Project,
    /// `[build]`
    pub build: BuildSection,
    /// `[link]`
    pub link: LinkSection,
    /// `[sim]`
    pub sim: SimSection,
    /// `[flash]`
    pub flash: FlashSection,
}

/// `[flash]` — how to reach the board when downloading.
#[derive(Debug, Clone)]
pub struct FlashSection {
    /// Serial port, for example `/dev/ttyUSB0` or `COM3`.
    pub port: String,
    /// Bootloader dialect: `stc89` or `stc12`.
    pub protocol: String,
    /// Transfer baud rate.
    pub baud: u32,
    /// Baud rate used to find the chip.
    pub handshake_baud: u32,
    /// Reset mode: `manual`, `dtr`, `rts`, `dtr_inverted`, `rts_inverted`.
    pub reset: String,
    /// Option (fuse) byte to write. `None` keeps whatever the chip reports.
    pub option: Option<u8>,
    /// Whether to write the option byte at all.
    pub write_options: bool,
    /// Flash size of the part, in bytes, used to reject an oversized image.
    pub flash_size: usize,
}

impl Default for FlashSection {
    fn default() -> Self {
        Self {
            port: String::new(),
            protocol: "stc89".into(),
            baud: 115_200,
            handshake_baud: 2400,
            // A USB-TTL adapter wired the usual way resets the board when DTR
            // pulses, which is how the reference tools drive it.
            reset: "manual".into(),
            option: None,
            write_options: true,
            flash_size: 8192,
        }
    }
}

/// `[project]`
#[derive(Debug, Clone)]
pub struct Project {
    /// Project name, used for output file names.
    pub name: String,
    /// Free-form device description.
    pub device: String,
    /// One-line description.
    pub description: String,
}

impl Default for Project {
    fn default() -> Self {
        Self {
            name: "firmware".into(),
            device: "8051".into(),
            description: String::new(),
        }
    }
}

/// `[build]`
#[derive(Debug, Clone)]
pub struct BuildSection {
    /// Assembly sources, in link order.
    pub sources: Vec<String>,
    /// `"asm"` (default) or `"rust"`.
    ///
    /// `rust` means the application is generated by a Rust program that is run
    /// with `cargo run` during the build.
    pub language: String,
    /// Which binary to run for a Rust project (`cargo run --bin`).
    /// Empty means "the package's default binary", i.e. `src/main.rs`.
    pub rust_bin: String,
    /// Output directory.
    pub out: String,
    /// Emit a listing file.
    pub listing: bool,
    /// Emit a map file.
    pub map: bool,
}

impl Default for BuildSection {
    fn default() -> Self {
        Self {
            sources: vec!["src/main.asm".into()],
            language: "asm".into(),
            rust_bin: String::new(),
            out: "build".into(),
            listing: true,
            map: true,
        }
    }
}

/// `[link]`
#[derive(Debug, Clone, Default)]
pub struct LinkSection {
    /// Linker script path, relative to the manifest.
    pub script: Option<String>,
    /// Address for a "the whole image sums to zero" checksum byte.
    pub checksum: Option<u16>,
}

/// `[sim]`
#[derive(Debug, Clone)]
pub struct SimSection {
    /// Instruction budget for `mcs51 run`.
    pub instructions: u64,
    /// Bytes to feed to the UART before running.
    pub input: String,
    /// Print a register dump when the run stops.
    pub dump: bool,
    /// Oscillator frequency the simulator should assume, in Hz. Decides how
    /// long a UART bit takes on the wire.
    pub cpu_hz: u32,
    /// Baud rate the simulated UART runs at.
    pub uart_baud: u32,
}

impl Default for SimSection {
    fn default() -> Self {
        Self {
            instructions: 200_000,
            input: String::new(),
            dump: true,
            cpu_hz: 11_059_200,
            uart_baud: 9600,
        }
    }
}

impl Manifest {
    /// The default manifest, used when no `mcs51.toml` is present.
    pub fn defaults(root: impl Into<PathBuf>) -> Self {
        let root = root.into();
        Self {
            path: root.join("mcs51.toml"),
            root,
            ..Self::default()
        }
    }

    /// Read and parse `mcs51.toml` from a directory.
    pub fn load(dir: impl AsRef<Path>) -> Result<Self, ManifestError> {
        let root = dir.as_ref().to_path_buf();
        let path = root.join("mcs51.toml");
        let text = std::fs::read_to_string(&path).map_err(|e| ManifestError {
            line: 0,
            message: format!("cannot read {}: {e}", path.display()),
        })?;
        Self::parse(&text, root)
    }

    /// Parse a manifest.
    pub fn parse(text: &str, root: impl Into<PathBuf>) -> Result<Self, ManifestError> {
        let root = root.into();
        let mut fields: BTreeMap<String, BTreeMap<String, Value>> = BTreeMap::new();
        let mut section = String::new();

        for (index, raw) in text.lines().enumerate() {
            let line_no = index + 1;
            let content = strip_comment(raw);
            if let Some(column) = bare_semicolon(content) {
                return Err(ManifestError {
                    line: line_no,
                    message: format!(
                        "TOML 的注释符号是 `#`，不是 `;`（第 {} 列）。\
                         把这一行里的 `;` 改成 `#`：\n      {}",
                        column + 1,
                        content.trim_end()
                    ),
                });
            }
            let line = content.trim();
            if line.is_empty() {
                continue;
            }
            if let Some(name) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
                section = name.trim().to_ascii_lowercase();
                fields.entry(section.clone()).or_default();
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                return Err(ManifestError {
                    line: line_no,
                    message: format!("expected `key = value`, found `{line}`"),
                });
            };
            let parsed = parse_value(value.trim()).ok_or_else(|| ManifestError {
                line: line_no,
                message: format!("cannot parse value `{}`", value.trim()),
            })?;
            fields
                .entry(section.clone())
                .or_default()
                .insert(key.trim().to_ascii_lowercase(), parsed);
        }

        let get = |section: &str, key: &str| -> Option<&Value> {
            fields.get(section).and_then(|s| s.get(key))
        };
        let string = |section: &str, key: &str, default: &str| -> String {
            match get(section, key) {
                Some(Value::Str(s)) => s.clone(),
                Some(Value::Int(i)) => i.to_string(),
                Some(Value::Bool(b)) => b.to_string(),
                _ => default.to_string(),
            }
        };
        let int = |section: &str, key: &str, default: i64| -> i64 {
            match get(section, key) {
                Some(Value::Int(i)) => *i,
                Some(Value::Str(s)) => s.parse().unwrap_or(default),
                _ => default,
            }
        };
        let boolean = |section: &str, key: &str, default: bool| -> bool {
            match get(section, key) {
                Some(Value::Bool(b)) => *b,
                Some(Value::Int(i)) => *i != 0,
                Some(Value::Str(s)) => matches!(s.as_str(), "true" | "yes" | "on" | "1"),
                _ => default,
            }
        };
        let list = |section: &str, key: &str| -> Option<Vec<String>> {
            match get(section, key) {
                Some(Value::List(items)) => Some(items.clone()),
                Some(Value::Str(s)) => Some(vec![s.clone()]),
                _ => None,
            }
        };

        let default_build = BuildSection::default();
        let default_sim = SimSection::default();

        let project = Project {
            name: string("project", "name", "firmware"),
            device: string("project", "device", "8051"),
            description: string("project", "description", ""),
        };
        let build = BuildSection {
            sources: list("build", "sources").unwrap_or(default_build.sources),
            language: string("build", "language", &default_build.language).to_ascii_lowercase(),
            rust_bin: string("build", "rust_bin", &default_build.rust_bin),
            out: string("build", "out", &default_build.out),
            listing: boolean("build", "listing", default_build.listing),
            map: boolean("build", "map", default_build.map),
        };
        let link = LinkSection {
            script: match get("link", "script") {
                Some(Value::Str(s)) if !s.is_empty() => Some(s.clone()),
                _ => None,
            },
            checksum: match get("link", "checksum") {
                Some(Value::Int(i)) => Some(*i as u16),
                _ => None,
            },
        };
        let sim = SimSection {
            instructions: int("sim", "instructions", default_sim.instructions as i64) as u64,
            input: string("sim", "input", ""),
            dump: boolean("sim", "dump", default_sim.dump),
            cpu_hz: int("sim", "cpu_hz", default_sim.cpu_hz as i64) as u32,
            uart_baud: int("sim", "uart_baud", default_sim.uart_baud as i64) as u32,
        };

        let default_flash = FlashSection::default();
        let flash = FlashSection {
            port: string("flash", "port", &default_flash.port),
            protocol: string("flash", "protocol", &default_flash.protocol),
            baud: int("flash", "baud", default_flash.baud as i64) as u32,
            handshake_baud: int(
                "flash",
                "handshake_baud",
                default_flash.handshake_baud as i64,
            ) as u32,
            reset: string("flash", "reset", &default_flash.reset),
            option: match get("flash", "option") {
                Some(Value::Int(value)) => Some(*value as u8),
                _ => None,
            },
            write_options: boolean("flash", "write_options", default_flash.write_options),
            flash_size: int("flash", "flash_size", default_flash.flash_size as i64) as usize,
        };

        Ok(Manifest {
            path: root.join("mcs51.toml"),
            root,
            project,
            build,
            link,
            sim,
            flash,
        })
    }

    /// Resolve a manifest-relative path.
    pub fn resolve(&self, relative: &str) -> PathBuf {
        let path = Path::new(relative);
        if path.is_absolute() {
            path.to_path_buf()
        } else {
            self.root.join(path)
        }
    }

    /// The output directory.
    pub fn out_dir(&self) -> PathBuf {
        self.resolve(&self.build.out)
    }
}

#[derive(Debug, Clone)]
enum Value {
    Str(String),
    Int(i64),
    Bool(bool),
    List(Vec<String>),
}

/// Why a manifest could not be read.
#[derive(Debug, Clone)]
pub struct ManifestError {
    /// 1-based line number, or 0 for whole-file problems.
    pub line: usize,
    /// What went wrong.
    pub message: String,
}

impl fmt::Display for ManifestError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.line == 0 {
            f.write_str(&self.message)
        } else {
            write!(f, "line {}: {}", self.line, self.message)
        }
    }
}

impl std::error::Error for ManifestError {}

/// TOML 的注释符只有 `#`。
///
/// 这里**故意不接受** `;`：那会让一份非法清单在我们眼里看起来没问题，
/// 而编辑器、linter 和任何别的 TOML 工具都会报错。见 [`bare_semicolon`]。
fn strip_comment(line: &str) -> &str {
    let mut quote = false;
    for (i, c) in line.char_indices() {
        match c {
            '"' => quote = !quote,
            '#' if !quote => return &line[..i],
            _ => {}
        }
    }
    line
}

/// 找出行内**引号之外**的第一个 `;`，返回它的字节位置。
///
/// TOML 没有 `;` 注释，所以出现在这里的 `;` 一定是写错了。字符串里的
/// `;` 不受影响（例如 `path = "/dev/tty;0"`）。
fn bare_semicolon(line: &str) -> Option<usize> {
    let mut quote = false;
    for (i, c) in line.char_indices() {
        match c {
            '"' => quote = !quote,
            ';' if !quote => return Some(i),
            _ => {}
        }
    }
    None
}

fn parse_value(text: &str) -> Option<Value> {
    let text = text.trim();
    if let Some(inner) = text.strip_prefix('[').and_then(|t| t.strip_suffix(']')) {
        let items = inner
            .split(',')
            .map(|item| item.trim().trim_matches('"').to_string())
            .filter(|item| !item.is_empty())
            .collect();
        return Some(Value::List(items));
    }
    if (text.starts_with('"') && text.ends_with('"') && text.len() >= 2)
        || (text.starts_with('\'') && text.ends_with('\'') && text.len() >= 2)
    {
        return Some(Value::Str(text[1..text.len() - 1].to_string()));
    }
    if text.eq_ignore_ascii_case("true") {
        return Some(Value::Bool(true));
    }
    if text.eq_ignore_ascii_case("false") {
        return Some(Value::Bool(false));
    }
    if let Some(hex) = text.strip_prefix("0x").or_else(|| text.strip_prefix("0X")) {
        return i64::from_str_radix(hex, 16).ok().map(Value::Int);
    }
    if let Ok(value) = text.parse::<i64>() {
        return Some(Value::Int(value));
    }
    if text.is_empty() {
        return None;
    }
    // Bare words are treated as strings so `script = linker.lk` works.
    Some(Value::Str(text.to_string()))
}

