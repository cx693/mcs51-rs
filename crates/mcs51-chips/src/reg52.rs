/// 从 SFR 和位序号定义位 —— 位地址由 [`Bit::of`] 推出来，不手写。
macro_rules! bits {
    ($($name:ident = $sfr:ident ^ $index:literal, $doc:literal;)*) => {
        $(
            #[doc = $doc]
            pub const $name: Bit = Bit::of(stringify!($name), $sfr, $index, $doc);
        )*

        /// 本模块定义的全部位。
        pub static BITS: &[Bit] = &[$($name),*];
    };
}

