; ===========================================================================
;  blink.asm -- mcs51-rs 裸机示例
;
;  P1.0 每约 0.5 秒翻转一次，同时每轮往串口打一行十六进制计数。
;
;  **这是一个真正的裸机程序**：复位向量 + 中断向量表 + 主程序。
;  没有调度器、没有系统节拍、没有运行时 —— 要什么自己用指令搭。
;
;  构建： mcs51 build
;  运行： mcs51 run
; ===========================================================================

        .area CODE (ABS)
        .org  0x0000
        LJMP  main                   ; 复位向量

; ---------------------------------------------------------------------------
; 中断向量表：本工程不用中断，但必须填上 —— 万一有干扰触发中断，
; 落到未初始化的 0xFF 上就会跑飞。
; ---------------------------------------------------------------------------
        .org  0x0003
        RETI                         ; INT0
        .org  0x000B
        RETI                         ; Timer 0
        .org  0x0013
        RETI                         ; INT1
        .org  0x001B
        RETI                         ; Timer 1
        .org  0x0023
        RETI                         ; 串口
        .org  0x002B
        RETI                         ; Timer 2

; ---------------------------------------------------------------------------
; main
;
; 这一版用**轮询**而不是中断：先把 UART 配上，主循环里
; "翻引脚 → 报数 → 延时"。没有中断就没有并发，逻辑一眼看得完。
; ---------------------------------------------------------------------------
        .org  0x0030
main:
        MOV   SP, #0x30              ; 复位后 SP=0x07，必须重设，
                                     ; 否则第一次压栈会覆盖寄存器组 1

        ACALL uart_init              ; 11.0592MHz / 9600 8N1
        MOV   R4, #0                 ; R4 = 计数

main_loop:
        CPL   P1_0                   ; 翻转 P1.0
        ACALL report                 ; 打一行 "t=NN\r\n"
        INC   R4
        ACALL delay_500ms
        SJMP  main_loop

; ---------------------------------------------------------------------------
; report -- 打印 "t=" + R4 的两位十六进制 + 回车换行
; ---------------------------------------------------------------------------
report:
        MOV   DPTR, #prefix
        ACALL puts
        MOV   A, R4
        ACALL put_hex2
        MOV   DPTR, #crlf
        ACALL puts
        RET

; ---------------------------------------------------------------------------
; uart_init -- Timer 1 模式 2 做波特率发生器，SCON 模式 1
;
;   baud = (2^SMOD / 32) * fosc / (12 * (256 - TH1))
;   11.0592MHz、SMOD=0、9600 baud  →  256 - TH1 = 3  →  TH1 = 0xFD
;   11.0592MHz 之所以是 8051 的标准晶振，正因为这个除法能整除、误差为 0；
;   12MHz 下同样的 9600 只能做到 10417（+8.5%）。
; ---------------------------------------------------------------------------
uart_init:
        MOV   TMOD, #0x20            ; Timer 1 模式 2（8 位自动重装）
        MOV   TH1, #0xFD
        MOV   TL1, #0xFD
        MOV   SCON, #0x50            ; 模式 1（8 位 UART）+ REN
        MOV   PCON, #0x00            ; SMOD = 0
        SETB  TR1                    ; 启动波特率发生器
        RET

; ---------------------------------------------------------------------------
; putc -- 发送 A 里的一个字节（轮询 TI）
; ---------------------------------------------------------------------------
putc:
        MOV   SBUF, A
putc_wait:
        JNB   TI, putc_wait          ; 等发送完成
        CLR   TI
        RET

; ---------------------------------------------------------------------------
; puts -- 发送 DPTR 指向的 NUL 结尾字符串
; 破坏：A、DPTR
; ---------------------------------------------------------------------------
puts:
        CLR   A
        MOVC  A, @A+DPTR
        JZ    puts_done
        ACALL putc
        INC   DPTR
        SJMP  puts
puts_done:
        RET

; ---------------------------------------------------------------------------
; put_hex2 -- 把 A 打印成两位十六进制
; 破坏：A、R7
; ---------------------------------------------------------------------------
put_hex2:
        MOV   R7, A                  ; 留着低 4 位
        SWAP  A
        ACALL put_nibble             ; 先打高 4 位
        MOV   A, R7
        ; 落到 put_nibble 打印低 4 位
put_nibble:
        ANL   A, #0x0F
        ADD   A, #0x30               ; 数字 0..9 的 ASCII 就是 0x30+n
        CJNE  A, #0x3A, put_nibble_check
put_nibble_check:
        JC    put_nibble_send        ; 还是数字
        ADD   A, #7                  ; '9'(0x39) 之后跳到 'A'(0x41)，差 7
put_nibble_send:
        ACALL putc
        RET

; ---------------------------------------------------------------------------
; delay_500ms -- 三层空循环，11.0592MHz 下约 0.5 秒
;
;   DJNZ 是 2 个机器周期；1 个机器周期 = 12 / 11.0592MHz ≈ 1.085us
;   4 × 250 × 250 × 2 ≈ 500,000 个机器周期 ≈ 0.54 秒
; ---------------------------------------------------------------------------
delay_500ms:
        MOV   R5, #4
delay_outer:
        MOV   R6, #250
delay_middle:
        MOV   R7, #250
delay_inner:
        DJNZ  R7, delay_inner
        DJNZ  R6, delay_middle
        DJNZ  R5, delay_outer
        RET

prefix: .db   "t=", 0
crlf:   .db   0x0D, 0x0A, 0
        .end
