//! 通用 80C52 / 80C32 —— Keil `reg52.h` 的 Rust 版。
//!
//! 这是 8051 世界的"基础款"：任何一颗 8052 兼容片子上这些寄存器和位都在。
//! 具体型号（STC、AT、NXP…）的扩展定义在别的模块里，通过
//! [`CHIP`] 的 `base` 字段继承这里。
//!
//! 每个条目的说明都来自厂商头文件 —— 那才是这个库真正的价值。

use crate::{Bit, Chip, Sfr};

// ---------------------------------------------------------------------------
// 字节寄存器（sfr）
// ---------------------------------------------------------------------------

macro_rules! sfrs {
    ($($name:ident = $addr:literal, $doc:literal;)*) => {
        $(
            #[doc = $doc]
            pub const $name: Sfr = Sfr { name: stringify!($name), addr: $addr, doc: $doc };
        )*

        /// 本模块定义的全部字节寄存器。
        pub static SFR: &[Sfr] = &[$($name),*];
    };
}

